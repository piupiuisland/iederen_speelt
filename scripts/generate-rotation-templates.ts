// Builds the built-in rotation templates by simulating every option.
// Run: npm run templates   (rewrites src/domain/engine/rotationTemplates.data.ts)
//
// For each (children present, players on the field, match length) we simulate a
// day of 3 matches with a "perfect parent" for every swap interval (5–8 min)
// and every number
// of children per swap, then pick the best by:
//   cost = playing-time difference (min) + 2 × swap moments per match
// Ties: fewer swaps, then the most even stretches between swaps, then the
// longer interval. Swap times follow plannedSubTimes (first ≥ 6′, none in the last 4′).
import { writeFileSync } from "node:fs";
import { MINUTE, plannedSubTimes } from "../src/domain/settings.ts";
import { simulateMatchDay } from "../src/domain/simulate.ts";

const PRESENT = [5, 6, 7, 8];
const ON_FIELD = [4, 5, 6];
const LENGTHS = [15, 20, 30, 40];
// At least 5 min between swaps (more often is too hectic for young children),
// at most 8 min waiting on the bench.
const INTERVALS = [5, 6, 7, 8];
const MATCHES = 3;

interface Row {
  present: number;
  onField: number;
  matchMin: number;
  intervalMin: number;
  swapsPerSub: number;
  differenceMin: number;
  swapMomentsPerMatch: number;
}

const rows: Row[] = [];
for (const present of PRESENT)
  for (const onField of ON_FIELD) {
    const bench = present - onField;
    if (bench < 1) continue;
    for (const matchMin of LENGTHS) {
      const candidates: (Row & { cost: number; unevenness: number; swapsPerMatch: number })[] = [];
      for (const intervalMin of INTERVALS)
        for (let swapsPerSub = 1; swapsPerSub <= Math.min(bench, 4); swapsPerSub++) {
          const r = simulateMatchDay({
            playerCount: present,
            matchDurationsMs: Array.from({ length: MATCHES }, () => matchMin * MINUTE),
            settings: { playersOnField: onField, reminderIntervalMs: intervalMin * MINUTE, maxSubsPerRecommendation: swapsPerSub },
          });
          const moments = new Set(r.substitutions.map((s) => `${s.matchNumber}:${s.elapsedMs}`)).size / MATCHES;
          const differenceMin = Math.round(r.fairness.rangeMs / MINUTE);
          const cuts = [0, ...plannedSubTimes(matchMin * MINUTE, intervalMin * MINUTE), matchMin * MINUTE];
          const segments = cuts.slice(1).map((t, i) => (t - cuts[i]!) / MINUTE);
          candidates.push({
            present,
            onField,
            matchMin,
            intervalMin,
            swapsPerSub,
            differenceMin,
            swapMomentsPerMatch: Math.round(moments * 10) / 10,
            cost: differenceMin + 2 * moments,
            swapsPerMatch: r.substitutions.length / MATCHES,
            unevenness: Math.max(...segments) - Math.min(...segments),
          });
        }
      candidates.sort(
        (a, b) =>
          a.cost - b.cost ||
          a.swapsPerMatch - b.swapsPerMatch ||
          a.unevenness - b.unevenness ||
          b.intervalMin - a.intervalMin,
      );
      const { cost: _c, unevenness: _u, swapsPerMatch: _s, ...best } = candidates[0]!;
      rows.push(best);
      console.log(
        `${present} present, ${onField} on field, ${matchMin}′: every ${best.intervalMin} min × ${best.swapsPerSub}` +
          ` (difference ${best.differenceMin} min, ${best.swapMomentsPerMatch} swap moments/match)`,
      );
    }
  }

const out = `// GENERATED by scripts/generate-rotation-templates.ts — do not edit by hand.
// Simulated: ${MATCHES} matches per day, swap interval ${INTERVALS[0]}–${INTERVALS.at(-1)} min.
import type { RotationTemplate } from "./rotation.ts";

export const ROTATION_TEMPLATES: readonly RotationTemplate[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/domain/engine/rotationTemplates.data.ts", import.meta.url), out);
console.log(`\nWrote ${rows.length} templates.`);
